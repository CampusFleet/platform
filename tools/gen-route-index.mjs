#!/usr/bin/env node
/**
 * Regenerates docs/ROUTES.md: every page and API route, with HTTP methods,
 * the middleware access rule, and how many files call each API path.
 * Usage: node tools/gen-route-index.mjs
 */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const appDir = path.join(root, "src/app");
const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

const srcFiles = walk(path.join(root, "src")).filter((f) => /\.(ts|tsx)$/.test(f) && !f.includes(`${path.sep}test${path.sep}`));
const text = new Map(srcFiles.map((f) => [f, fs.readFileSync(f, "utf8")]));
const toUrl = (dir) => "/" + path.relative(appDir, dir).split(path.sep).filter((s) => !/^\(.*\)$/.test(s)).join("/");

const accessSrc = fs.readFileSync(path.join(root, "src/lib/security/api-access.ts"), "utf8");
const rules = [...accessSrc.matchAll(/prefix:\s*"([^"]+)",\s*(roles|write):\s*([^}]+?)\s*}/g)].map((m) => ({ prefix: m[1], kind: m[2], who: m[3].trim() }));
const publicPrefixes = [...(accessSrc.match(/PUBLIC_PREFIXES = \[([\s\S]*?)\];/)?.[1] || "").matchAll(/"([^"]+)"/g)].map((m) => m[1]);
const accessFor = (url) => {
  if (publicPrefixes.some((p) => url === p || url.startsWith(p))) return "public (handler auth)";
  const r = rules.filter((x) => url === x.prefix || url.startsWith(x.prefix + "/")).sort((a, b) => b.prefix.length - a.prefix.length)[0];
  if (!r) return "any session";
  return r.kind === "roles" ? `roles: ${r.who}` : `writes: ${r.who}`;
};

const pages = srcFiles.filter((f) => f.startsWith(appDir) && path.basename(f) === "page.tsx").map((f) => toUrl(path.dirname(f))).sort();

const apis = srcFiles
  .filter((f) => f.startsWith(path.join(appDir, "api")) && path.basename(f) === "route.ts")
  .map((f) => {
    const url = toUrl(path.dirname(f));
    const methods = [...text.get(f).matchAll(/export (?:async )?(?:function|const) (GET|POST|PUT|PATCH|DELETE|HEAD)\b/g)].map((m) => m[1]);
    const re = new RegExp(url.replace(/[.*+?^${}()|\\]/g, "\\$&").replace(/\\\[[^\]]+\\\]|\[[^\]]+\]/g, "[^\"'`/?]+") + "(?=[\"'`?/]|\\$\\{|$)");
    const callers = srcFiles.filter((g) => !g.startsWith(path.dirname(f) + path.sep) && !g.endsWith("api-access.ts") && re.test(text.get(g))).length;
    return { url, methods: [...new Set(methods)].join(", "), access: accessFor(url), callers };
  })
  .sort((a, b) => a.url.localeCompare(b.url));

const out = [
  "# Routes (generated — do not edit by hand)",
  "",
  `Generated by \`node tools/gen-route-index.mjs\` on ${new Date().toISOString().slice(0, 10)}. ${pages.length} pages, ${apis.length} API routes.`,
  "",
  "`callers` = files under src/ (excluding tests) that reference the path. 0 usually means dead, unless the route is called by a device, webhook, OAuth redirect or cron (see vercel.json).",
  "",
  "## Pages",
  "",
  ...pages.map((p) => `- \`${p}\``),
  "",
  "## API routes",
  "",
  "| Route | Methods | Middleware access | Callers |",
  "|---|---|---|---|",
  ...apis.map((a) => `| \`${a.url}\` | ${a.methods} | ${a.access} | ${a.callers} |`),
  "",
];
fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/ROUTES.md"), out.join("\n"));
console.log(`docs/ROUTES.md: ${pages.length} pages, ${apis.length} API routes`);
