#!/usr/bin/env bash
# Regenerates src/lib/database.types.ts from the production database schema.
# Usage: tools/gen-db-types.sh   (needs `vercel env pull` access; never commit the pulled env file)
set -euo pipefail
tmp=$(mktemp)
vercel env pull "$tmp" --environment=production --yes >/dev/null
url=$(grep '^POSTGRES_PRISMA_URL=' "$tmp" | cut -d= -f2- | tr -d '"'); rm -f "$tmp"
{ echo "// Generated by tools/gen-db-types.sh from the live database. Do not edit by hand."
  npx -y supabase@latest gen types typescript --db-url "${url%%\?*}" --schema public 2>/dev/null; } > src/lib/database.types.ts
echo "src/lib/database.types.ts updated"
